USE bookstore;
-- Thêm loại ngoại lệ GHN_CANCELLED (GHN/cửa hàng hủy vận đơn từ phía GHN trong khi đơn vẫn đang xử lý)
SET @c = (SELECT COUNT(*) FROM information_schema.CHECK_CONSTRAINTS WHERE CONSTRAINT_SCHEMA=DATABASE() AND CONSTRAINT_NAME='ck_exc_type' AND CHECK_CLAUSE LIKE '%GHN_CANCELLED%');
SET @s = IF(@c = 0, 'ALTER TABLE ExceptionItem DROP CHECK ck_exc_type', 'SELECT 1');
PREPARE st FROM @s; EXECUTE st; DEALLOCATE PREPARE st;
SET @s = IF(@c = 0, 'ALTER TABLE ExceptionItem ADD CONSTRAINT ck_exc_type CHECK (type IN (''UNKNOWN_SEPAY_TXN'',''REFUND_PAYOUT_FAILED'',''REFUND_VNPAY_FAILED'',''RETURN_MISMATCH'',''GHN_CLAIM_FAILED'',''GHN_RECONCILE_COD'',''GHN_RECONCILE_FEE'',''GHN_LOST'',''GHN_CANCELLED''))', 'SELECT 1');
PREPARE st FROM @s; EXECUTE st; DEALLOCATE PREPARE st;
